using System.Diagnostics;
using System.IO;
using System.Reflection;
using System.Text.Json;
using System.Windows;
using System.Windows.Controls;
using System.Windows.Threading;
using Teclas.Core;

namespace Teclas.App;

public partial class App
{
    // Karaoke line, accelerating metronome and the measure-by-measure report. No MuseScore or MIDI device runs.
    private async void VerifyV037Ui(string reportPath)
    {
        ShutdownMode = ShutdownMode.OnExplicitShutdown;
        string report = Path.GetFullPath(reportPath), reports = Path.GetDirectoryName(report)!;
        Directory.CreateDirectory(reports);
        string work = Path.Combine(Directory.GetParent(reports)!.FullName, "work", "v037-" + Guid.NewGuid().ToString("N")[..8]);
        Directory.CreateDirectory(work);
        var checks = new Dictionary<string, bool>();
        MainWindow? window = null; PracticeWindow? practice = null;
        var timeout = new DispatcherTimer { Interval = TimeSpan.FromSeconds(60) };
        timeout.Tick += (_, _) => { File.WriteAllText(report, JsonSerializer.Serialize(new { status = "failed", checks, error = "v0.37 smoke timed out." })); Shutdown(1); };
        timeout.Start();
        void Check(bool condition, string name) { if (!condition) throw new InvalidOperationException(name); checks.Add(name, true); }
        void Flush() => Dispatcher.Invoke(() => { }, DispatcherPriority.ApplicationIdle);
        async Task Wait(Func<bool> predicate, string what)
        {
            var clock = Stopwatch.StartNew();
            while (!predicate() && clock.Elapsed < TimeSpan.FromSeconds(10)) await Task.Delay(10);
            if (!predicate()) throw new TimeoutException(what);
            Flush();
        }
        try
        {
            // Karaoke: syllables in order, the line of the current and next measure, the sung one marked.
            MusicEvent E(int measure, double quarter, string lyric, bool continues = false) =>
                new($"e{measure}-{quarter}", 1, measure, 1, quarter, "Chord", "quarter", 0, [], true, "") { DurationQuarter = 1, Lyric = lyric, LyricContinues = continues };
            var model = new NativeMusicModel("x.mscz", "", null!, [
                new MusicMeasure(1, 1, "", [E(1, 0, "Ca", true), E(1, 1, "sa"), E(1, 2, "ri", true), E(1, 3, "nho")], []),
                new MusicMeasure(1, 2, "", [E(2, 0, "da"), E(2, 2, "ro", true), E(2, 3, "ça")], []),
                new MusicMeasure(1, 3, "", [E(3, 0, "sol")], [])], []);
            var syllables = KaraokeLyrics.FromScore(model);
            Check(syllables.Count == 8 && syllables[0] is { Text: "Ca", Continues: true }, "karaoke-reads-the-syllables");
            var line = KaraokeLyrics.Line(syllables, 1, 1.5);
            Check(string.Concat(line.Select(p => p.Text)).Trim() == "Ca-sa ri-nho da ro-ça" && line[1].State == KaraokeState.Current && line[0].State == KaraokeState.Sung && line[2].State == KaraokeState.Coming, "karaoke-line-marks-the-current-syllable");
            Check(KaraokeLyrics.Line(syllables, 3, 0).Select(p => p.Text.Trim()).SequenceEqual(new[] { "sol" }), "karaoke-moves-with-the-music");

            // Optional native check: a score generated by MuseScore with lyrics keeps every syllable in order.
            if (Environment.GetEnvironmentVariable("TECLAS_TEST_LYRIC_SCORE") is { Length: > 0 } lyricScore && File.Exists(lyricScore))
            {
                var real = KaraokeLyrics.FromScore(NativeMusicEditor.Open(lyricScore, CancellationToken.None));
                Check(real.Count == 18 && real[0] is { Text: "Ca", Continues: true } && real[1].Text == "sa", $"native-score-lyrics-for-karaoke ({real.Count})");
            }

            // Karaoke in the main window: map position → line over the preview.
            string settingsPath = Path.Combine(work, "settings.json");
            new Settings { OutputDirectory = Path.Combine(work, "saida"), Karaoke = true, FollowScorePlayback = true }.Save(settingsPath);
            window = new MainWindow(true, settingsPath) { Opacity = 0, ShowInTaskbar = false, ShowActivated = false, Width = 1300, Height = 900 };
            window.Show(); Flush();
            string midi = Path.Combine(work, "letra.mid"); File.WriteAllBytes(midi, SyntheticTwoTrackMidi());
            window.ImportForSmoke(midi); Flush();
            var row = window.Files.Single(); string score = Path.Combine(work, "letra.mscz"); File.WriteAllBytes(score, [1]); row.ScorePath = score;
            ((ListBox)window.FindName("Library")).SelectedItem = null; Flush(); ((ListBox)window.FindName("Library")).SelectedItem = row; Flush();
            var timeline = new[] { new ScorePlaybackOccurrence(0, 1, 0, 2, null), new ScorePlaybackOccurrence(1, 2, 2, 4, null), new ScorePlaybackOccurrence(2, 3, 4, 6, null) };
            var map = new ScorePlaybackMap(score, "", 1, [], [], [], timeline, [], true) { MeasureTimeline = timeline };
            const BindingFlags hidden = BindingFlags.Instance | BindingFlags.NonPublic;
            typeof(MainWindow).GetField("scorePlaybackMap", hidden)!.SetValue(window, map);
            typeof(MainWindow).GetField("karaokeModel", hidden)!.SetValue(window, new Func<string, NativeMusicModel>(_ => model));
            window.UpdateKaraoke(.75);
            await Wait(() => window.KaraokeLine.Count > 0, "karaoke line did not appear");
            var viewer = (ScoreViewer)window.FindName("MainScoreViewer");
            Check(window.KaraokeLine.Single(p => p.State == KaraokeState.Current).Text == "sa " && ((Border)viewer.FindName("KaraokeBar")).Visibility == Visibility.Visible
                && ((TextBlock)viewer.FindName("KaraokeText")).Inlines.Count == window.KaraokeLine.Count, "karaoke-shows-over-the-preview");
            window.KaraokeEnabled = false; Flush();
            Check(((Border)viewer.FindName("KaraokeBar")).Visibility == Visibility.Collapsed, "karaoke-off-hides-the-line");
            window.Close(); window = null;

            // Practice: measure report and accelerating metronome.
            PracticeStep S(int measure, double start, int pitch) => new(measure, start % 4, [pitch]) { Start = start };
            var steps = new[] { S(1, 0, 60), S(1, 1, 62), S(2, 4, 64), S(2, 5, 65) };
            practice = new PracticeWindow("Prova", steps, [], true, 60) { ShowActivated = false, ShowInTaskbar = false, Opacity = 0, TempoGoal = 70 };
            practice.clickOutput = () => null;
            practice.Show(); Flush();
            practice.Choose(PracticeMode.Notes, true, 60); Flush();
            practice.Play(60, 0); practice.Play(61, .5); practice.Play(64, 4); practice.Play(65, 5); practice.Tick(6);
            Check(practice.LastReport.Count == 2 && practice.LastReport[0] is { Measure: 1, Missed: 1, Wrong: 1 } && practice.LastReport[1].Clean, "report-per-measure");
            MeasureReportWindow? shown = null;
            practice.reportDialog = dialog => { shown = dialog; dialog.Choose(); return true; };
            ((Button)LogicalChildren(practice).OfType<Button>().First(b => (b.Content as string) == "Ver compassos")).RaiseEvent(new RoutedEventArgs(Button.ClickEvent)); Flush();
            Check(shown?.ChosenMeasure == 1 && practice.Passage is { From: 1, To: 1 } && practice.Session.Steps.Count == 2, "report-chooses-a-measure-to-train");
            practice.ChoosePassage("", "", false); practice.ChooseAccelerate(true); practice.Choose(PracticeMode.Notes, true, 60); Flush();
            practice.Play(60, 0); practice.Play(62, 1); practice.Play(64, 4); practice.Play(65, 5); practice.Tick(6);
            await Wait(() => practice.Bpm == 65 && practice.Timed is { Bpm: 65 }, "tempo did not rise after a clean pass");
            Check(practice.Bpm == 65, "clean-pass-raises-the-tempo");
            CaptureFolderWindow(practice, Path.Combine(reports, "practice-accelerate.png"));
            practice.Close(); practice = null;
            File.WriteAllText(report, JsonSerializer.Serialize(new { status = "passed", checks, enginesRun = 0 }, new JsonSerializerOptions { WriteIndented = true }));
            Shutdown(0);
        }
        catch (Exception error)
        {
            File.WriteAllText(report, JsonSerializer.Serialize(new { status = "failed", checks, error = error.ToString() }, new JsonSerializerOptions { WriteIndented = true }));
            practice?.Close(); window?.Close(); Shutdown(1);
        }
        finally { timeout.Stop(); }
    }

    private static IEnumerable<DependencyObject> LogicalChildren(DependencyObject root)
    {
        foreach (var child in LogicalTreeHelper.GetChildren(root).OfType<DependencyObject>())
        {
            yield return child;
            foreach (var nested in LogicalChildren(child)) yield return nested;
        }
    }
}
